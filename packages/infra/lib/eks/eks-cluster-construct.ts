import { KubectlV35Layer } from '@aws-cdk/lambda-layer-kubectl-v35';
import * as eks from 'aws-cdk-lib/aws-eks-v2';
import { Construct } from 'constructs';
import { INetwork } from '../network';
import { IWorkloadCluster } from './workload-cluster';

/**
 * The kubectl layer must match the cluster's Kubernetes version, so the two
 * are defined together. Upgrade both at once (and the
 * `@aws-cdk/lambda-layer-kubectl-vXX` dependency).
 */
const KUBERNETES_VERSION = eks.KubernetesVersion.V1_35;
const createKubectlLayer = (scope: Construct) => new KubectlV35Layer(scope, 'KubectlLayer');

export interface EksClusterConstructProps {
  /** Network to place the cluster in. The control plane ENIs use the private subnets. */
  readonly network: INetwork;

  /**
   * Name of the EKS cluster.
   * @default - generated by CloudFormation
   */
  readonly clusterName?: string;
}

/**
 * Provisions an EKS cluster (Auto Mode) with a kubectl provider, so that
 * manifests and Helm charts can be applied. Exposes the workload-facing
 * surface through `IWorkloadCluster`.
 */
export class EksClusterConstruct extends Construct implements IWorkloadCluster {
  /**
   * The underlying cluster, for platform-level configuration (access entries,
   * add-ons, capacity, ...). Workload constructs should depend on
   * `IWorkloadCluster` instead.
   */
  public readonly cluster: eks.Cluster;

  public readonly clusterName: string;

  constructor(scope: Construct, id: string, props: EksClusterConstructProps) {
    super(scope, id);

    this.cluster = new eks.Cluster(this, 'Cluster', {
      clusterName: props.clusterName,
      version: KUBERNETES_VERSION,
      vpc: props.network.vpc,
      vpcSubnets: [{ subnets: props.network.privateSubnets }],
      // Without a kubectl provider, addManifest/addHelmChart would fail, so
      // it's always configured here.
      kubectlProviderOptions: {
        kubectlLayer: createKubectlLayer(this),
      },
    });

    this.clusterName = this.cluster.clusterName;
  }

  public addManifest(id: string, ...manifest: Record<string, any>[]): eks.KubernetesManifest {
    return this.cluster.addManifest(id, ...manifest);
  }

  public addHelmChart(id: string, options: eks.HelmChartOptions): eks.HelmChart {
    return this.cluster.addHelmChart(id, options);
  }
}
